// Hardware latency and throughput benchmark.
// Cycle 0 is the first rising edge after time zero. An operation is accepted
// on an edge where start && !busy is true. Completion is the edge on which
// done rises. latency_cycles = completion_cycle - acceptance_cycle.
`timescale 1ns/1ps
module math_accelerator_tb;
    localparam integer NUM_SAMPLES = 100;
    localparam integer NUM_OPS = 12;
    localparam integer CLOCK_PERIOD_NS = 10;

    reg clk, reset, start;
    reg [3:0] opcode;
    reg [31:0] a,b,c,d,e,f;
    wire [31:0] result,result_imag;
    wire busy,done,valid;
    wire [7:0] error;

    math_accelerator dut(
        .clk(clk), .reset(reset), .start(start), .opcode(opcode),
        .operand_a(a), .operand_b(b), .operand_c(c), .operand_d(d),
        .operand_e(e), .operand_f(f), .result(result), .result_imag(result_imag),
        .busy(busy), .done(done), .valid(valid), .error(error)
    );

    integer cycle_counter;
    integer accept_cycle;
    integer current_op;
    integer sample_index;
    integer completion_seen;
    integer latency_samples [0:11][0:99];
    integer gap_sum [0:11];
    integer previous_accept [0:11];
    integer accepted_count [0:11];
    integer have_previous [0:11];
    integer i;
    integer csvfd, wavefd;
    reg fp_wave_start, complex_wave_start, cordic_wave_start;

    always #5 clk = ~clk;

    function [127:0] operation_name;
        input [3:0] op;
        begin
            case (op)
                0: operation_name = "FP_ADD";
                1: operation_name = "FP_SUB";
                2: operation_name = "FP_MUL";
                3: operation_name = "FP_MAC";
                4: operation_name = "C_ADD";
                5: operation_name = "C_SUB";
                6: operation_name = "C_MUL";
                7: operation_name = "C_MAC";
                8: operation_name = "C_CONJ";
                9: operation_name = "SIN";
                10: operation_name = "COS";
                11: operation_name = "ATAN2";
                default: operation_name = "INVALID";
            endcase
        end
    endfunction

    // This monitor evaluates acceptance using the DUT's pre-edge busy value,
    // which is the actual synchronous handshake condition.
    always @(posedge clk) begin
        cycle_counter = cycle_counter + 1;
        if (start && !busy) begin
            accept_cycle = cycle_counter;
            accepted_count[current_op] = accepted_count[current_op] + 1;
            if (have_previous[current_op])
                gap_sum[current_op] = gap_sum[current_op] +
                                      cycle_counter - previous_accept[current_op];
            previous_accept[current_op] = cycle_counter;
            have_previous[current_op] = 1;
            if ((current_op == 0) && !fp_wave_start) begin
                $fwrite(wavefd, "FP_START cycle=%0d time_ns=%0d\n", cycle_counter, cycle_counter*CLOCK_PERIOD_NS+5);
                fp_wave_start = 1;
            end else if ((current_op == 4) && !complex_wave_start) begin
                $fwrite(wavefd, "COMPLEX_START cycle=%0d time_ns=%0d\n", cycle_counter, cycle_counter*CLOCK_PERIOD_NS+5);
                complex_wave_start = 1;
            end else if ((current_op == 9) && !cordic_wave_start) begin
                $fwrite(wavefd, "CORDIC_START cycle=%0d time_ns=%0d\n", cycle_counter, cycle_counter*CLOCK_PERIOD_NS+5);
                cordic_wave_start = 1;
            end
        end
    end

    // done is generated by a clocked nonblocking assignment. Its rising edge
    // occurs in the same simulation time slot as the completion clock edge,
    // after the DUT updates, so this records the actual completion edge.
    always @(posedge done) begin
        if (current_op >= 0 && current_op < NUM_OPS) begin
            latency_samples[current_op][sample_index] = cycle_counter - accept_cycle;
            completion_seen = 1;
            if ((current_op == 0) && fp_wave_start && (sample_index == 0))
                $fwrite(wavefd, "FP_DONE cycle=%0d time_ns=%0d\n", cycle_counter, cycle_counter*CLOCK_PERIOD_NS+5);
            else if ((current_op == 4) && complex_wave_start && (sample_index == 0))
                $fwrite(wavefd, "COMPLEX_DONE cycle=%0d time_ns=%0d\n", cycle_counter, cycle_counter*CLOCK_PERIOD_NS+5);
            else if ((current_op == 9) && cordic_wave_start && (sample_index == 0))
                $fwrite(wavefd, "CORDIC_DONE cycle=%0d time_ns=%0d\n", cycle_counter, cycle_counter*CLOCK_PERIOD_NS+5);
        end
    end

    task configure_operands;
        input [3:0] op;
        begin
            a = 32'h3f800000; b = 32'h40000000; c = 32'h40400000;
            d = 32'h40800000; e = 32'h3f800000; f = 32'h3f800000;
            case (op)
                0: begin a=32'h3f800000; b=32'h40000000; end       // 1+2
                1: begin a=32'h40b00000; b=32'h40100000; end       // 5.5-2.25
                2: begin a=32'h3fc00000; b=32'h40000000; end       // 1.5*2
                3: begin a=32'h40000000; b=32'h40400000; c=32'h3f800000; end
                4,5,6: begin end                                  // 1+j2, 3+j4
                7: begin end                                      // plus 1+j1
                8: begin end                                      // conjugate 1+j2
                9,10: begin a=32'h00000000; end                  // sin/cos(0)
                11: begin a=32'h3f800000; b=32'h00000000; end     // atan2(1,0)
                default: begin end
            endcase
        end
    endtask

    task run_batch;
        input [3:0] op;
        integer n;
        integer watchdog;
        begin
            current_op = op;
            for (n = 0; n < NUM_SAMPLES; n = n + 1) begin
                sample_index = n;
                opcode = op;
                configure_operands(op);
                while (busy) @(posedge clk);
                @(negedge clk);
                start = 1;
                @(posedge clk);
                #1 start = 0;
                // The done edge sets completion_seen in the monitor. Waiting
                // on that flag avoids inserting an artificial full-cycle
                // bubble before the next request.
                wait (completion_seen == 1);
                completion_seen = 0;
            end
        end
    endtask

    task write_statistics;
        input [3:0] op;
        integer n,j,k,tmp;
        integer sum_cycles;
        real average, median, variance, stddev, average_gap, throughput, latency_ns;
        begin
            // Sort the measured samples to obtain the median.
            for (k = 0; k < NUM_SAMPLES; k = k + 1)
                for (j = k + 1; j < NUM_SAMPLES; j = j + 1)
                    if (latency_samples[op][j] < latency_samples[op][k]) begin
                        tmp = latency_samples[op][k];
                        latency_samples[op][k] = latency_samples[op][j];
                        latency_samples[op][j] = tmp;
                    end
            sum_cycles = 0;
            for (n = 0; n < NUM_SAMPLES; n = n + 1)
                sum_cycles = sum_cycles + latency_samples[op][n];
            average = sum_cycles / 100.0;
            median = (latency_samples[op][49] + latency_samples[op][50]) / 2.0;
            variance = 0.0;
            for (n = 0; n < NUM_SAMPLES; n = n + 1)
                variance = variance + (latency_samples[op][n] - average) *
                                      (latency_samples[op][n] - average);
            stddev = $sqrt(variance / NUM_SAMPLES);
            average_gap = gap_sum[op] / 99.0;
            throughput = 1.0 / average_gap;
            latency_ns = average * CLOCK_PERIOD_NS;
            case (op)
                0: $fwrite(csvfd, "FP_ADD,"); 1: $fwrite(csvfd, "FP_SUB,");
                2: $fwrite(csvfd, "FP_MUL,"); 3: $fwrite(csvfd, "FP_MAC,");
                4: $fwrite(csvfd, "C_ADD,"); 5: $fwrite(csvfd, "C_SUB,");
                6: $fwrite(csvfd, "C_MUL,"); 7: $fwrite(csvfd, "C_MAC,");
                8: $fwrite(csvfd, "C_CONJ,"); 9: $fwrite(csvfd, "SIN,");
                10: $fwrite(csvfd, "COS,"); 11: $fwrite(csvfd, "ATAN2,");
            endcase
            $fwrite(csvfd, "%0d,%0d,%0.3f,%0.3f,%0.6f,%0.3f,%0.6f,%0.6f,%0d\n",
                    latency_samples[op][0],
                    latency_samples[op][99], average, median, stddev, latency_ns,
                    throughput, average_gap, ((op >= 9) ? 28 : 0));
            $display("%-8s min=%0d max=%0d avg=%0.3f median=%0.3f stddev=%0.6f latency_ns=%0.3f throughput=%0.6f results/cycle",
                     operation_name(op), latency_samples[op][0], latency_samples[op][99],
                     average, median, stddev, latency_ns, throughput);
        end
    endtask

    initial begin
        clk=0; reset=1; start=0; opcode=0;
        a=0;b=0;c=0;d=0;e=0;f=0;
        cycle_counter=-1; accept_cycle=0; current_op=0; sample_index=0;
        completion_seen=0; fp_wave_start=0; complex_wave_start=0; cordic_wave_start=0;
        for (i=0; i<NUM_OPS; i=i+1) begin
            gap_sum[i]=0; previous_accept[i]=0; accepted_count[i]=0; have_previous[i]=0;
        end
        csvfd = $fopen("results/latency.csv", "w");
        wavefd = $fopen("results/waveform_markers.txt", "w");
        $fwrite(csvfd, "operation,min_cycles,max_cycles,avg_cycles,median_cycles,stddev_cycles,latency_ns,throughput_results_per_cycle,avg_accept_interval_cycles,cordic_iterations\n");
        $dumpfile("results/latency.vcd");
        $dumpvars(0, math_accelerator_tb);
        repeat (3) @(posedge clk);
        reset=0;
        for (i=0; i<NUM_OPS; i=i+1) run_batch(i[3:0]);
        for (i=0; i<NUM_OPS; i=i+1) write_statistics(i[3:0]);
        $fclose(csvfd);
        $fclose(wavefd);
        $display("math_accelerator_tb PASS: latency measurements written to results/latency.csv");
        $display("LATENCY BENCHMARK COMPLETE: %0d samples/op, T=%0d ns", NUM_SAMPLES, CLOCK_PERIOD_NS);
        #1 $finish;
    end
endmodule
